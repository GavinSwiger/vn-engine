"""F07 step 5 — choices at 60 fps (``04-technical.md`` §11, §15 "Perf"; ``06-acceptance.md``
§1.7, §5): AC-F07-43 (``perf``), plus CI guards.

The game is ``gen_choice_bench.py``'s: F04's six-sprite bench scene and a looping menu of
six two-line choices of 60 characters (W47 warns about each in a dev run: they are two-line
on purpose). The harness is F04's (``stage_bench_harness.py``), subclassed:
``ChoiceBenchHarness`` posts a Down key at every frame start while a menu is open (so the
focus changes every frame, the costliest input: a new focused shape position each frame),
and a Return every ``pick_s`` seconds instead (the pick; the menu loops back at once). A
``MenuListener`` (``ChoiceController.add_listener``, ``04`` §5.5) marks each menu's open
frame (``menu_shown``, the first draw), each focus change, and each pick. A frame's work is
``App.recent.last_work_ms()`` read at the next frame start, as F05's bench does.

**CI guards (every run, in process, ``scripted_app``, fake clock, art at 1/5):** the
generated choices are 60 characters and two lines; the harness picks and moves the focus
as it should; the only warnings are the six W47s; each open frame is found.

**Reference runs (``perf``; the ADR-0005 machine or a stand-in with integrated graphics and
a PassMark single-thread score ≤ 2,000, never CI).** Close other apps, mains power,
"Balanced" plan, a 1920×1080 display at 100%, then (Windows, from the project root)::

    .venv/Scripts/python tests/perf/gen_choice_bench.py --seed 1
    set SDL_VIDEODRIVER=windows
    set VN_PERF=1
    set VN_PASSMARK_ST=<the machine's PassMark single-thread score>
    .venv/Scripts/python -m pytest tests/perf/test_choice_perf.py -m perf -s -v

(``SDL_VIDEODRIVER=x11`` or ``cocoa`` elsewhere; the tests fail under the dummy driver.)
AC-F07-43 is two 600 s runs (about 21 minutes; the fullscreen one takes the screen):
1280×720 windowed and 1920×1080 fullscreen. Each must meet invariant 10 (frame-work p99
≤ 16.0 ms, long frames ≤ 0.5%) and every open frame's work must be ≤ 10 ms. The game is
generated by the test when ``tests/perf/choice_bench/`` is missing or stale.
``VN_BENCH_SECONDS=N`` shortens the runs for a trial; such a run is not a result.
``docs/process/manual-F07.md`` lists the rest.
"""

import os
from dataclasses import dataclass, field
from pathlib import Path

import pygame
import pytest

from engine.app.app import App
from engine.core.constants import BENCH_WARMUP_S
from tests.fakes.loop import post_key
from tests.perf import gen_choice_bench as gen
from tests.perf.stage_bench_harness import (StageBenchHarness, bench_launch, machine_lines,
                                            parse_bench, scripted_play)
from tests.perf.test_text_bench import p99
from tests.script.load_process import cpu_name

SMALL = 5                                # CI guards' art scale
PICK_S = 2.0                             # AC-F07-43: a pick every 2 s
WORK_P99_MAX_MS = 16.00                  # ADR-0005, invariant 10
LONG_PCT_MAX = 0.50
OPEN_WORK_MAX_MS = 10.0                  # AC-F07-43: every open frame's work
MEASURED_TOLERANCE_S = 0.05


@dataclass
class ChoiceBenchHarness(StageBenchHarness):
    """F04's harness with no ``Advance``: Down every frame while a menu is open, Return
    every ``pick_s`` seconds."""

    pick_s: float = PICK_S
    work_ms: list[float] = field(default_factory=list)       # [i]: frame i's work
    opened: list[int] = field(default_factory=list)          # frame index of each first draw
    focus_frames: list[int] = field(default_factory=list)    # frame index of each change
    picks: int = 0
    downs: int = 0
    returns: int = 0
    _listening: bool = False
    _next_pick: float | None = None

    # MenuListener (04 §5.5)
    def menu_shown(self, cmd) -> None:
        self.opened.append(len(self.frames) - 1)

    def focus_changed(self, key) -> None:
        self.focus_frames.append(len(self.frames) - 1)

    def picked(self, key) -> None:
        self.picks += 1

    def on_frame(self, app: App, now: float) -> None:
        if self.frames:
            self.work_ms.append(app.recent.last_work_ms())
        super().on_frame(app, now)
        choices = getattr(app, "choices", None)
        if choices is None or self.story_started is None:
            return
        if not self._listening:
            choices.add_listener(self)
            self._listening = True
        if self._next_pick is None:
            self._next_pick = self.story_started + self.pick_s
        if choices.screen is None:
            return
        if now >= self._next_pick:
            post_key(pygame.K_RETURN)
            self.returns += 1
            while self._next_pick <= now:
                self._next_pick += self.pick_s
        else:
            post_key(pygame.K_DOWN)
            self.downs += 1

    # --- the report ------------------------------------------------------------------------

    def after_warmup(self, indices: list[int]) -> list[int]:
        if self.story_started is None:
            return []
        start = self.story_started + BENCH_WARMUP_S
        return [i for i in indices if self.frames[i] >= start]

    def open_work_ms(self, *, warmup: bool = True) -> list[float]:
        """The work of each menu's open frame (frames with a recorded work only)."""
        indices = self.after_warmup(self.opened) if warmup else self.opened
        return [self.work_ms[i] for i in indices if i < len(self.work_ms)]


def _ms(values: list[float]) -> str:
    if not values:
        return "none"
    ordered = sorted(values)
    return (f"{len(ordered)} frames | ms p50 {ordered[len(ordered) // 2]:.3f} | "
            f"p99 {p99(ordered):.3f} | max {ordered[-1]:.3f}")


def _report(title: str, harness: ChoiceBenchHarness) -> None:
    print(f"\n== {title}")
    for line in machine_lines(cpu_name(), os.environ.get("VN_PASSMARK_ST"), harness.driver):
        print(line)
    for line in harness.bench_lines:
        print(line)
    print(f"Menus opened: {len(harness.opened)} | picks: {harness.picks} | focus changes: "
          f"{len(harness.focus_frames)} | Downs posted: {harness.downs}")
    print("Open frames' work: " + _ms(harness.open_work_ms()))


def _w47_only(warnings: list[str]) -> bool:
    return len(warnings) == gen.CHOICES and all(
        w.startswith("WARNING vn.choice: ") and "this choice needs 2 lines" in w
        for w in warnings)


# --- CI guards ------------------------------------------------------------------------------

def test_choice_texts_are_sixty_characters_and_distinct():
    texts = gen.choice_texts(1)
    assert len(texts) == gen.CHOICES == len(set(texts))
    assert all(len(t) == gen.CHOICE_CHARS for t in texts)
    assert gen.choice_texts(1) == texts                            # seeded


@pytest.mark.display
def test_the_harness_moves_focus_every_frame_and_picks(tmp_path, user_roots, scripted_app):
    """The small game for 4 s of fake frames, a pick every 0.5 s: menus open and are
    picked, the focus changes in (nearly) every frame a menu is open, and the launch's
    only warnings are W47's two-line form for the six choices."""
    game = gen.generate(tmp_path / "choice_bench", seed=1, scale=SMALL)
    harness = ChoiceBenchHarness(advance_s=None, pick_s=0.5)
    assert scripted_play(scripted_app, game, harness, frames=240) == 0
    assert _w47_only(harness.warnings), harness.warnings
    assert harness.returns >= 5 and harness.picks >= 5
    assert len(harness.opened) == harness.picks + 1                 # the loop reopens it
    assert len(harness.focus_frames) >= harness.downs * 0.9
    assert len(harness.open_work_ms(warmup=False)) >= harness.picks


# --- AC-F07-43 (perf) ------------------------------------------------------------------------

def _fresh(folder: Path) -> bool:
    stamp = folder / gen.stage.STAMP
    script = folder / "script" / "main.vns"
    return (stamp.is_file() and stamp.read_text(encoding="utf-8") == gen.stage.stamp(1, 1)
            and script.is_file() and script.read_text(encoding="utf-8") == gen.script_text(1))


@pytest.fixture(scope="module")
def choice_game():
    """``tests/perf/choice_bench/`` at seed 1 (generated if missing or stale); its config
    is put back to windowed afterwards."""
    root = gen.OUT
    if not _fresh(root):
        gen.generate(root, seed=1)
    yield root
    (root / "config.toml").write_text(gen.config_text(), encoding="utf-8", newline="\n")


@pytest.mark.perf
@pytest.mark.parametrize("fullscreen", [False, True], ids=["1280x720-windowed",
                                                           "1920x1080-fullscreen"])
def test_ac_f07_43_six_two_line_choices_at_60_fps(choice_game, real_display, user_roots,
                                                    fullscreen):
    seconds = float(os.environ.get("VN_BENCH_SECONDS", "600"))
    (choice_game / "config.toml").write_text(gen.config_text(fullscreen=fullscreen),
                                             encoding="utf-8", newline="\n")
    harness = ChoiceBenchHarness(advance_s=None)
    code = bench_launch(choice_game, harness, seconds=seconds)
    _report(f"AC-F07-43 {'1920x1080 fullscreen' if fullscreen else '1280x720 windowed'} "
            f"({seconds:.0f} s)", harness)
    assert code == 0 and _w47_only(harness.warnings), harness.warnings
    bench = parse_bench(harness.bench_lines)
    if fullscreen:
        assert bench["mode"] == "fullscreen" and bench["framebuffer"] == (1920, 1080)
    else:
        assert bench["mode"] == "windowed" and bench["window"] == (1280, 720)
    assert abs(bench["measured_s"] - seconds) <= MEASURED_TOLERANCE_S
    assert harness.picks >= seconds / PICK_S * 0.9
    assert bench["cap_holds"]
    assert bench["work_p99"] <= WORK_P99_MAX_MS
    assert bench["long_pct"] <= LONG_PCT_MAX
    opens = harness.open_work_ms()
    assert opens and max(opens) <= OPEN_WORK_MAX_MS, max(opens)
