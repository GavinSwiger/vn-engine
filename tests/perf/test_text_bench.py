_runs: dict[tuple[bool, int], tuple[int, TextBenchHarness, float]] = {}


def bench_run(root: Path, *, fullscreen: bool, cps: int) -> tuple[int, TextBenchHarness, float]:
    """One AC-F05-44 run, once per session (AC-F05-45 reuses the 1920×1080 ones)."""
    key = (fullscreen, cps)
    if key not in _runs:
        seconds = float(os.environ.get("VN_BENCH_SECONDS", "600"))
        game = root / f"cps{cps}"
        (game / "config.toml").write_text(config_text(cps, fullscreen=fullscreen),
                                          encoding="utf-8", newline="\n")
        harness = TextBenchHarness(advance_s=None)
        with pytest.MonkeyPatch.context() as mp, spy_textbox(harness, mp):
            code = bench_launch(game, harness, seconds=seconds)
        _report(f"AC-F05-44 {'1920x1080 fullscreen' if fullscreen else '1280x720 windowed'} "
                f"{cps} cps ({seconds:.0f} s)", harness)
        _runs[key] = (code, harness, seconds)
    return _runs[key]


def _ms(values: list[float]) -> str:
    if not values:
        return "none"
    ordered = sorted(values)
    return (f"{len(ordered)} frames | ms p50 {ordered[len(ordered) // 2]:.3f} | "
            f"p99 {p99(ordered):.3f} | max {ordered[-1]:.3f}")


def _report(title: str, harness: TextBenchHarness) -> None:
    print(f"\n== {title}")
    for line in machine_lines(cpu_name(), os.environ.get("VN_PASSMARK_ST"), harness.driver):
        print(line)
    for line in harness.bench_lines:
        print(line)
    measured = harness.measured()
    print(f"Presses: {harness.presses} | lines shown: {len(harness.said)}")
    print("F05 share, steady typing frames: " + _ms(harness.steady_ms()))
    print("F05 share, arrival frames: " + _ms([r.ms for r in measured if r.shown]))
    print("F05 share, all frames: " + _ms([r.ms for r in measured]))
    print("F10 quick menu (hosted overlays, not in the F05 share), steady typing frames: "
          + _ms(harness.steady_overlay_ms()))


