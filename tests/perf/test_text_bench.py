@pytest.mark.display
@pytest.mark.parametrize("cps", gen.CPS)
def test_each_press_completes_or_advances(small, user_roots, scripted_app, cps):
    """The harness's press is the player's: at 40 cps a 3-line line (about 200 graphemes,
    5 s) is completed by one press and left by the next; at 1,000 cps (0.2 s) every press
    advances. Each line arrives in exactly one frame, never a steady typing frame."""
    game = small[f"cps{cps}"]
    harness = TextBenchHarness(advance_s=None, press_s=0.5)          # every 30 frames
    assert play(scripted_app, game, harness, frames=200) == 0
    assert harness.warnings == []
    assert harness.presses >= 5
    lines = len(harness.said)
    assert lines == (1 + harness.presses // 2 if cps == 40 else 1 + harness.presses)
    assert sum(1 for r in harness.f05.values() if r.shown) == lines
    steady = [r for r in harness.f05.values() if r.steady]
    assert steady and not any(r.shown or r.acted for r in steady)
    assert len(harness.steady_ms(warmup=False)) == len(steady)
    # The quick menu is timed on its own line, outside the textbox share.
    assert all(0.0 < r.overlay_ms < r.update_ms + r.draw_ms for r in steady)


@pytest.mark.display
def test_long_line_restore_and_skip_show_the_last_page(small, user_roots, scripted_app):
    """AC-F05-45's game and harness at 1920×1080: the line has 10,000 graphemes (one W40,
    its overflow warning); a restore, then a skip, each show its last page complete in the
    event's frame; that frame takes ≤ 300 ms of real time (G13's CI guard)."""
    game = small[LONG_GAME]
    (game / "config.toml").write_text(config_text(40, size=(1920, 1080),
                                                  art_height=gen.stage.ART_HEIGHT // SMALL),
                                      encoding="utf-8", newline="\n")
    harness = LongLineHarness(advance_s=None, wanted=2, act_s=0.1, settle_s=0.2, short_s=0.05)
    assert play(scripted_app, game, harness, frames=240) == 0
    assert len(harness.warnings) == 1 and "text boxes" in harness.warnings[0]
    assert [e.kind for e in harness.events] == ["restore", "skip"]
    long_says = [s for s in harness.said if len(s.text) > 1000]
    assert [s.restored for s in long_says] == [False, True, False]
    assert all(page == last and last > 10 and state is TypeState.COMPLETE
               for page, last, state in harness.shown_after), harness.shown_after
    assert len(harness.shown_after) == 2
    for event in harness.events:
        real_ms = (harness.real[event.index + 1] - harness.real[event.index]) * 1000.0
        assert real_ms <= CI_EVENT_MAX_MS, (event.kind, real_ms)


