# --- the harnesses -------------------------------------------------------------------------

@dataclass
class F05Frame:
    update_ms: float = 0.0               # TextboxScreen.update, its overlays' updates included
    draw_ms: float = 0.0                 # TextboxScreen.draw, its overlays' draws included
    overlay_ms: float = 0.0              # the hosted F10 overlays' update + draw (quick menu)
    typing: bool = False                 # the typer was TYPING when the update began
    shown: bool = False                  # a Say arrived (``show``; restored ones too)
    acted: bool = False                  # a press, restore or skip at the frame start

    @property
    def ms(self) -> float:
        """The textbox share (AC-F05-45): the screen's own update and draw (box, name tab,
        typed layer, glyphs, indicator, typing), without the F10 overlays it hosts."""
        return self.update_ms + self.draw_ms - self.overlay_ms

    @property
    def steady(self) -> bool:
        return self.typing and not self.shown and not self.acted


@dataclass
class TextBenchHarness(StageBenchHarness):
    """F04's harness with a press every ``press_s`` seconds once the story runs."""

    press_s: float | None = PRESS_S
    f05: dict[int, F05Frame] = field(default_factory=dict)   # by index into ``frames``
    work_ms: list[float] = field(default_factory=list)       # [i]: frame i's work (App.recent)
    real: list[float] = field(default_factory=list)          # perf_counter at each frame start
    said: list[Say] = field(default_factory=list)
    presses: int = 0
    _next_press: float | None = None

    def frame(self) -> F05Frame:
        return self.f05.setdefault(len(self.frames) - 1, F05Frame())

    def on_frame(self, app: App, now: float) -> None:
        if self.frames:
            self.work_ms.append(app.recent.last_work_ms())
        self.real.append(time.perf_counter())
        super().on_frame(app, now)
        if self.press_s is None or self.story_started is None or app.textbox is None:
            return
        if self._next_press is None:
            self._next_press = self.story_started + self.press_s
        if now >= self._next_press:
            self.press(app)
            while self._next_press <= now:
                self._next_press += self.press_s

    def press(self, app: App) -> None:
        if app.textbox.line is not None:
            app.textbox.press()
            self.presses += 1
            self.frame().acted = True

    # --- the report ------------------------------------------------------------------------

    def measured(self) -> list[F05Frame]:
        """Frames after the bench's warm-up (the story starts in the bench's first frame)."""
        if self.story_started is None:
            return []
        start = self.story_started + BENCH_WARMUP_S
        return [r for i, r in sorted(self.f05.items()) if 0 <= i < len(self.frames)
                and self.frames[i] >= start]

    def steady_ms(self, *, warmup: bool = True) -> list[float]:
        frames = self.measured() if warmup else list(self.f05.values())
        return sorted(r.ms for r in frames if r.steady)

    def steady_overlay_ms(self) -> list[float]:
        """The F10 overlays' time (the quick menu) in the same steady typing frames."""
        return sorted(r.overlay_ms for r in self.measured() if r.steady)


@dataclass
class Event:
    kind: str                            # "restore" or "skip"
    index: int                           # into ``frames``
    start: float


@dataclass
class LongLineHarness(TextBenchHarness):
    """AC-F05-45's long line, by turns restored and skipped ``act_s`` into its typing; the
    line is left ``settle_s`` after; the short lines around it are pressed on when complete.
    Quits ``settle_s`` after the last of ``wanted`` events."""

    press_s: float | None = None
    wanted: int = 6
    act_s: float = 1.0
    settle_s: float = 1.5
    short_s: float = 0.5
    events: list[Event] = field(default_factory=list)
    # (page shown, last page, typer state) in the frame after each event.
    shown_after: list[tuple[int, int, TypeState]] = field(default_factory=list)
    _phase: str = "wait"                 # "wait" → "typing" (checkpoint taken) → "acted"
    _checkpoint: object = None
    _due: float = 0.0
    _last_short: float = 0.0

    def on_frame(self, app: App, now: float) -> None:
        super().on_frame(app, now)
        box, story = app.textbox, app.story
        index = len(self.frames) - 1
        if self.events and index == self.events[-1].index + 1:
            # The line as the event's frame drew it.
            self.shown_after.append((box.typer.page, box.layout.all_pages() - 1,
                                     box.typer.state))
        if self.story_started is None or box is None or box.line is None:
            return
        line, typer = box.line, box.typer
        if len(self.events) >= self.wanted and self._phase == "wait":
            if now >= self._due:
                app.request_quit(force=True)
            return
        long = len(line.text) > 1000
        if self._phase == "wait":
            if long and not line.restored and typer.state is TypeState.TYPING:
                self._checkpoint = story.checkpoint()
                self._phase, self._due = "typing", now + self.act_s
            elif (not long and typer.state is TypeState.COMPLETE
                  and now - self._last_short >= self.short_s):
                self.press(app)
                self._last_short = now
        elif self._phase == "typing" and now >= self._due:
            kind = "restore" if len(self.events) % 2 == 0 else "skip"
            if kind == "restore":
                outcome = story.restore(self._checkpoint)
                assert outcome.result.name == "OK", outcome
            else:
                box.complete_now()
            self.frame().acted = True
            self.events.append(Event(kind, index, now))
            self._phase, self._due = "acted", now + self.settle_s
        elif self._phase == "acted" and now >= self._due:      # leave the line
            self.press(app)
            self._phase, self._last_short = "wait", now
            self._due = now + self.settle_s          # the quit, after the last event

    def event_report(self, event: Event) -> tuple[int, float, float]:
        """(long frame intervals in the 1 s after, max work in that second, the event
        frame's F05 share) in ms."""
        longs = long_frames_after(self.frames, [event.start])[0]
        end = event.start + 1.0
        work = [self.work_ms[i] for i in range(event.index, len(self.work_ms))
                if self.frames[i] <= end]
        return longs, max(work), self.f05.get(event.index, F05Frame()).ms


@contextlib.contextmanager
def spy_textbox(harness: TextBenchHarness, mp) -> Iterator[None]:
    """Time ``TextboxScreen.update`` + ``draw`` and mark the frame's typing and arrivals.
    Patched on the class before the launch, so the router's ``Say`` handler (the bound
    ``show``) is the spy too. Each overlay the launch hands to ``add_overlay`` (F10's
    ``GameMenuKeys`` and ``QuickMenu``) gets its ``update`` and ``draw`` timed into
    ``overlay_ms``, which the textbox share leaves out."""
    real_update, real_draw, real_show = TextboxScreen.update, TextboxScreen.draw, \
        TextboxScreen.show
    real_add_overlay = TextboxScreen.add_overlay

    def add_overlay(self, overlay):
        o_update, o_draw = overlay.update, overlay.draw

        def timed_update(dt, *, frozen):
            started = time.perf_counter()
            o_update(dt, frozen=frozen)
            harness.frame().overlay_ms += (time.perf_counter() - started) * 1000.0

        def timed_draw(canvas, *, box_shown):
            started = time.perf_counter()
            o_draw(canvas, box_shown=box_shown)
            harness.frame().overlay_ms += (time.perf_counter() - started) * 1000.0

        mp.setattr(overlay, "update", timed_update)
        mp.setattr(overlay, "draw", timed_draw)
        real_add_overlay(self, overlay)

    def update(self, dt, *, is_top):
        record = harness.frame()
        record.typing = self.typer is not None and self.typer.state is TypeState.TYPING
        started = time.perf_counter()
        real_update(self, dt, is_top=is_top)
        record.update_ms += (time.perf_counter() - started) * 1000.0

    def draw(self, canvas):
        started = time.perf_counter()
        real_draw(self, canvas)
        harness.frame().draw_ms += (time.perf_counter() - started) * 1000.0

    def show(self, cmd):
        harness.frame().shown = True
        harness.said.append(cmd)
        real_show(self, cmd)

    mp.setattr(TextboxScreen, "update", update)
    mp.setattr(TextboxScreen, "draw", draw)
    mp.setattr(TextboxScreen, "show", show)
    mp.setattr(TextboxScreen, "add_overlay", add_overlay)
    yield


def p99(values: list[float]) -> float:
    """Nearest rank, as the engine's bench lines: sorted(xs)[ceil(0.99 n) − 1]."""
    ordered = sorted(values)
    return ordered[math.ceil(0.99 * len(ordered)) - 1]


# --- the long-line game ---------------------------------------------------------------------

def long_text(seed: int = 1) -> str:
    """Bench prose of exactly ``LONG_CHARS`` shown characters, with one bold, one italic,
    and one colored word (tags are not shown, so not counted)."""
    rng = random.Random(seed)
    words: list[str] = []
    count = -1
    while True:
        word = rng.choice(gen.WORDS)
        if count + 1 + len(word) > LONG_CHARS:
            break
        words.append(word)
        count += 1 + len(word)
    words[-1] += "." * (LONG_CHARS - count)
    words[3] = "{b}" + words[3] + "{/b}"
    words[10] = "{i}" + words[10] + "{/i}"
    words[20] = "{color=" + gen.TAG_COLOR + "}" + words[20] + "{/color}"
    return " ".join(words)


def long_source(text: str, width: int = 96) -> list[str]:
    """``text`` as one quoted line continued on more-indented lines (each break is one
    space; ``docs/script-language.md`` "Long lines"), under F02's 10,000-character limit."""
    lines, current = [], ""
    for word in text.split(" "):
        if current and len(current) + 1 + len(word) > width:
            lines.append(current)
            current = word
        else:
            current = f"{current} {word}" if current else word
    lines.append(current)
    out = ['    aki "' + lines[0]] + ["        " + line for line in lines[1:]]
    out[-1] += '"'
    return out


def long_script(seed: int = 1) -> str:
    stage = gen.stage
    out = ["# AC-F05-45's long line (tests/perf/test_text_bench.py).",
           *(f'define {tag} = Character("{stage.NAMES[tag]}", color="{color}")'
             for tag, color in zip(stage.TAGS, gen.NAME_COLORS)),
           "label start:",
           f"    scene bg {stage.BACKGROUNDS[0]}",
           *(f"    show {tag} {stage.EXPRESSIONS[0]} at {x}" for tag, x in zip(stage.TAGS,
                                                                            stage.XS)),
           "    jump loop",
           "label loop:",
           '    aki "Ready."',
           *long_source(long_text(seed)),
           '    ben "After."',
           "    jump loop"]
    return "\n".join(out) + "\n"


def config_text(cps: int, *, fullscreen: bool = False, size: tuple[int, int] | None = None,
                art_height: int = gen.stage.ART_HEIGHT) -> str:
    window = f"\n[window]\nfullscreen = {'true' if fullscreen else 'false'}\n"
    if size is not None:
        window += f"width = {size[0]}\nheight = {size[1]}\n"
    return gen.config_text(cps, art_height=art_height) + window


def write_long_game(out: Path, *, seed: int = 1, scale: int = 1) -> Path:
    """``out/long10k``: the art of ``out/cps40`` (written by ``gen.generate``), the long-line
    script, cps 40."""
    first, folder = out / f"cps{gen.CPS[0]}", out / LONG_GAME
    for ref in gen.stage.image_refs():
        gen._link_or_copy(first / ref, folder / ref)
    (folder / "script").mkdir(parents=True, exist_ok=True)
    (folder / "script" / "main.vns").write_text(long_script(seed), encoding="utf-8",
                                                newline="\n")
    (folder / "config.toml").write_text(
        config_text(40, art_height=gen.stage.ART_HEIGHT // scale), encoding="utf-8",
        newline="\n")
    (folder / gen.stage.STAMP).write_text(gen.stage.stamp(seed, scale), encoding="utf-8")
    return folder


def small_games(root: Path) -> dict[str, Path]:
    folders = gen.generate(root, seed=1, scale=SMALL)
    out = {folder.name: folder for folder in folders}
    out[LONG_GAME] = write_long_game(root, scale=SMALL)
    return out


def play(session, game: Path, harness: TextBenchHarness, *, frames: int) -> int:
    with pytest.MonkeyPatch.context() as mp, spy_textbox(harness, mp):
        return scripted_play(session, game, harness, frames=frames)


